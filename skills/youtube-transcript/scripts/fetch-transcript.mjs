#!/usr/bin/env node

/**
 * YouTube Transcript Fetcher
 * Uses yt-dlp to extract subtitles and metadata from YouTube videos.
 * Outputs structured JSON for the skill to process.
 *
 * Prerequisites: yt-dlp binary at /tmp/yt-dlp or on PATH
 * Install: curl -L https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_macos -o /tmp/yt-dlp && chmod +x /tmp/yt-dlp
 *
 * Usage: node fetch-transcript.mjs <youtube-url>
 */

import { execSync } from "child_process";
import { readFileSync, mkdirSync, existsSync, unlinkSync, readdirSync } from "fs";
import { join } from "path";

const url = process.argv[2];
if (!url) {
  console.error("Usage: fetch-transcript.mjs <youtube-url>");
  process.exit(1);
}

// Find yt-dlp
function findYtDlp() {
  const locations = ["/tmp/yt-dlp", "/usr/local/bin/yt-dlp", "/opt/homebrew/bin/yt-dlp"];
  for (const loc of locations) {
    if (existsSync(loc)) return loc;
  }
  // Check PATH
  try {
    const path = execSync("which yt-dlp 2>/dev/null", { encoding: "utf8" }).trim();
    if (path) return path;
  } catch {}
  return null;
}

const ytdlp = findYtDlp();
if (!ytdlp) {
  console.error(JSON.stringify({
    error: "yt-dlp not found",
    fix: "Run: curl -L https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_macos -o /tmp/yt-dlp && chmod +x /tmp/yt-dlp",
  }));
  process.exit(1);
}

// Temp dir for subtitle files
const tmpDir = join("/tmp", `yt-transcript-${Date.now()}`);
mkdirSync(tmpDir, { recursive: true });

try {
  // Step 1: Get metadata
  let metaRaw;
  try {
    metaRaw = execSync(
      `${ytdlp} --print "%(id)s|||%(title)s|||%(channel)s|||%(duration)s|||%(upload_date)s|||%(description).1000s|||%(webpage_url)s" --skip-download "${url}"`,
      { encoding: "utf8", timeout: 30000, stdio: "pipe" }
    ).trim();
  } catch (e) {
    const stderr = e.stderr?.toString() || e.message;
    if (stderr.includes("Video unavailable")) {
      console.error(JSON.stringify({ error: "Video unavailable or does not exist" }));
    } else if (stderr.includes("Private video")) {
      console.error(JSON.stringify({ error: "Video is private" }));
    } else {
      console.error(JSON.stringify({ error: "Failed to fetch video metadata", detail: stderr.slice(0, 300) }));
    }
    process.exit(1);
  }

  const [videoId, title, channel, durationSec, uploadDate, description, webUrl] =
    metaRaw.split("|||");

  const duration = parseInt(durationSec);
  const durationStr =
    duration >= 3600
      ? `${Math.floor(duration / 3600)}:${String(Math.floor((duration % 3600) / 60)).padStart(2, "0")}:${String(duration % 60).padStart(2, "0")}`
      : `${Math.floor(duration / 60)}:${String(duration % 60).padStart(2, "0")}`;

  // Step 2: Download subtitles — try manual first, then auto-generated
  // Note: yt-dlp exits 0 even when no subs found, so check files after each attempt
  try {
    execSync(
      `${ytdlp} --write-sub --sub-lang en --skip-download --sub-format json3 -o "${tmpDir}/subs" "${url}"`,
      { encoding: "utf8", timeout: 30000, stdio: "pipe" }
    );
  } catch { /* no manual subs */ }

  if (readdirSync(tmpDir).filter((f) => f.endsWith(".json3")).length === 0) {
    // No manual subs found — try auto-generated
    try {
      execSync(
        `${ytdlp} --write-auto-sub --sub-lang "en-orig,en" --skip-download --sub-format json3 -o "${tmpDir}/subs" "${url}"`,
        { encoding: "utf8", timeout: 30000, stdio: "pipe" }
      );
    } catch { /* no auto subs either */ }
  }

  // Find the subtitle file
  const subFiles = readdirSync(tmpDir).filter((f) => f.endsWith(".json3"));
  if (subFiles.length === 0) {
    console.error(JSON.stringify({
      error: "No English subtitles available for this video",
      videoId,
      title,
    }));
    process.exit(1);
  }

  const subData = JSON.parse(readFileSync(join(tmpDir, subFiles[0]), "utf8"));
  const isAutoGenerated = subFiles[0].includes(".en-orig") || subFiles[0].includes("auto");

  // Step 3: Parse segments
  const events = subData.events || [];
  const segments = [];

  for (const event of events) {
    if (!event.segs) continue;
    const text = event.segs
      .map((s) => s.utf8 || "")
      .join("")
      .trim();
    if (!text || text === "\n") continue;

    const startMs = event.tStartMs || 0;
    const startSec = startMs / 1000;
    const h = Math.floor(startSec / 3600);
    const m = Math.floor((startSec % 3600) / 60);
    const s = Math.floor(startSec % 60);
    const timestamp =
      h > 0
        ? `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`
        : `${m}:${String(s).padStart(2, "0")}`;

    segments.push({ start: startSec, timestamp, text: text.replace(/\n/g, " ") });
  }

  // Step 4: Build merged paragraphs (group segments into ~30-second blocks)
  const paragraphs = [];
  let currentParagraph = { timestamp: "", texts: [] };
  let blockStart = 0;

  for (const seg of segments) {
    if (seg.start - blockStart > 30 && currentParagraph.texts.length > 0) {
      paragraphs.push({
        timestamp: currentParagraph.timestamp,
        text: currentParagraph.texts.join(" "),
      });
      currentParagraph = { timestamp: seg.timestamp, texts: [] };
      blockStart = seg.start;
    }
    if (currentParagraph.texts.length === 0) {
      currentParagraph.timestamp = seg.timestamp;
      blockStart = seg.start;
    }
    currentParagraph.texts.push(seg.text);
  }
  if (currentParagraph.texts.length > 0) {
    paragraphs.push({
      timestamp: currentParagraph.timestamp,
      text: currentParagraph.texts.join(" "),
    });
  }

  // Output
  const result = {
    videoId,
    title,
    channel,
    url: webUrl,
    duration: durationStr,
    durationSeconds: duration,
    uploadDate: uploadDate
      ? `${uploadDate.slice(0, 4)}-${uploadDate.slice(4, 6)}-${uploadDate.slice(6, 8)}`
      : null,
    description,
    autoGenerated: isAutoGenerated,
    segmentCount: segments.length,
    paragraphCount: paragraphs.length,
    segments,
    paragraphs,
  };

  console.log(JSON.stringify(result, null, 2));
} finally {
  // Cleanup temp files
  try {
    const files = readdirSync(tmpDir);
    for (const f of files) unlinkSync(join(tmpDir, f));
    execSync(`rmdir "${tmpDir}" 2>/dev/null`);
  } catch {}
}
